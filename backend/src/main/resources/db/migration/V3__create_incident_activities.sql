
CREATE TABLE incident_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    incident_id BIGINT NOT NULL,

    action VARCHAR(50) NOT NULL,

    description TEXT NOT NULL,

    old_value VARCHAR(100),

    new_value VARCHAR(100),

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_incident_activities_incident
        FOREIGN KEY (incident_id)
        REFERENCES incidents(id)
        ON DELETE CASCADE
);

CREATE INDEX idx_incident_activities_incident_id
ON incident_activities(incident_id);

CREATE INDEX idx_incident_activities_created_at
ON incident_activities(created_at DESC);
